def update_schedule(
    action,
    event_id=None,
    date_value=None,
    time_value=None,
    title=None,
    event_type=None,
    description=None
):

    global schedule

    # ADD
    if action == "add":

        new_id = f"event_{len(schedule) + 1}"

        new_event = {
            "id": new_id,
            "date": date_value,
            "time": time_value,
            "title": title,
            "type": event_type or "task",
            "description": description or ""
        }

        schedule.append(new_event)

        rebuild_chroma()

        return (
            f"Added '{title}' on "
            f"{date_value} at {time_value}."
        )

    # UPDATE
    elif action == "update":

        event = next(
            (e for e in schedule if e["id"] == event_id),
            None
        )

        if not event:
            return "Event not found."

        if date_value:
            event["date"] = date_value

        if time_value:
            event["time"] = time_value

        if title:
            event["title"] = title

        if event_type:
            event["type"] = event_type

        if description:
            event["description"] = description

        rebuild_chroma()

        return (
            f"Updated '{event['title']}'. "
            f"New time: {event['date']} at {event['time']}."
        )

    # DELETE
    elif action == "delete":

        event = next(
            (e for e in schedule if e["id"] == event_id),
            None
        )

        if not event:
            return "Event not found."

        schedule.remove(event)

        rebuild_chroma()

        return f"Deleted '{event['title']}'."

    return "Invalid action."

