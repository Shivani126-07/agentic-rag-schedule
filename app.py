from google.genai import types

def run_agent(user_query):

    contents = [
        types.Content(
            role="user",
            parts=[
                types.Part.from_text(text=user_query)
            ]
        )
    ]

    # Allow multiple tool calls
    for step in range(5):

        response = client.models.generate_content(
            model="gemini-3.1-flash-lite",
            contents=contents,
            config={
                "tools": tools,
                "system_instruction": """
You are an Agentic Schedule Assistant.

You manage the user's schedule for the next 30 days.

Use get_schedule when the user asks about:
- existing events
- meetings
- workshops
- tasks
- appointments
- free time

Use update_schedule when the user wants to:
- add an event
- update an event
- move an event
- delete an event

For moving, updating, or deleting an existing event:
1. First use get_schedule.
2. Find the correct Event ID.
3. Then use update_schedule with that Event ID.
4. Give a short confirmation.

Never invent schedule information.
Keep answers short and clear.
"""
            }
        )

        # No tool required
        if not response.function_calls:
            return response.text

        # Add Gemini response
        contents.append(
            response.candidates[0].content
        )

        # Execute tools
        for function_call in response.function_calls:

            print("Tool selected:", function_call.name)
            print("Arguments:", function_call.args)

            if function_call.name == "get_schedule":

                result = get_schedule(
                    function_call.args["query"]
                )

            elif function_call.name == "update_schedule":

                result = update_schedule(
                    action=function_call.args.get("action"),
                    event_id=function_call.args.get("event_id"),
                    date_value=function_call.args.get("date_value"),
                    time_value=function_call.args.get("time_value"),
                    title=function_call.args.get("title"),
                    event_type=function_call.args.get("event_type"),
                    description=function_call.args.get("description")
                )

            else:
                result = "Unknown tool."

            print("Tool result:", result)

            # Send tool result back to Gemini
            function_response = types.Part.from_function_response(
                name=function_call.name,
                response={
                    "result": result
                }
            )

            contents.append(
                types.Content(
                    role="user",
                    parts=[function_response]
                )
            )

    return "I could not complete the request."

